export const MODE_LABELS={essay:'Tự luận',quiz:'Trắc nghiệm',scenario:'Tình huống',legacy:'Lượt cũ',synthesis:'Tổng hợp'};
export function modesFor(topic){
  if(topic.synthesis)return ['essay'];
  return exercises[topic.id]?['essay','quiz','scenario']:['essay','scenario'];
}
export function chooseMode(topic, preference, attempts){
  const modes=modesFor(topic);
  if(preference!=='auto')return modes.includes(preference)?preference:modes[0];
  const attemptsForTopic=attempts.filter(a=>a.topicId===topic.id&&modes.includes(a.mode)).length;
  return modes[attemptsForTopic%modes.length];
}
export function questionFor(topic,mode){
  if(mode==='quiz')return exercises[topic.id].quiz[0];
  if(mode==='scenario')return exercises[topic.id]?.scenario ??
    `Hãy nêu một tình huống cụ thể mà khái niệm “${topic.title}” giúp giải thích. Phân tích nguyên nhân, hệ quả và một giới hạn trước khi trả lời: ${topic.question}`;
  return topic.question;
}
